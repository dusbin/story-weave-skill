/** 术语名列表，供自检与文档使用 */
export const TERM_KEYS = Object.keys(TERMS);

/** 生成术语表 markdown */
export function renderTermsMd() {
  const L = ['# 术语表', ''];
  for (const key of TERM_KEYS) {
    const t = TERMS[key];
    if (key === 'shortDefs') continue;
    L.push(`- **${t.term}**（\`${key}\`）：${t.def}`);
  }
  L.push('');
  return L.join('\n');
}
