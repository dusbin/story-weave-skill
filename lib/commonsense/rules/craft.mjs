/**
 * lib/commonsense/rules/craft.mjs — 叙事逻辑类检查清单（id 前缀 CRAFT）。
 *
 * 本模块**全部使用 ask，不写 check**，这是刻意的设计：
 * "人物动机有没有铺垫""这个转折有没有因果链"这类问题需要读懂语义，
 * 正则判不了；硬判出来的每一条都是误报。引擎的契约正好为此设计——
 * 有 ask 而无 check 的规则不会产出 finding，而是产出一条带原文证据的 checklist 项，
 * 由模型回答并留痕（见 engine.mjs 的 makeChecklistItem）。
 *
 * 因此这里的写作重点是**问题本身要好回答**：
 *   问题必须指向"文中可指认的两处/一处原文"，并且能给出"是/否 + 依据"的答案；
 *   含糊的问题（"你觉得人物立体吗"）对作者没有价值。
 *
 * severity 只影响清单项的优先级显示；这些规则不会产出 finding。
 */

